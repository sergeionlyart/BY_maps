#!/usr/bin/env bash
# Единственная точка входа: воспроизводит соотношения полов по 118 районам,
# декомпозицию «умерли или уехали», вердикты H1-H4, пост-хок и гейты S-1…S-6
# из завендоренных переписей, прогноза v2026.4 и таблиц смертности; проверяет
# инварианты и сверяет с заявленным. Требования: Python >= 3.10, стандартная
# библиотека. Сеть не нужна.
set -euo pipefail
cd "$(dirname "$0")/.."
export PYTHONDONTWRITEBYTECODE=1
PY="${PYTHON:-python3}"

echo "== 1/3 Расчёт соотношений, декомпозиции, гипотез и гейтов =="
"$PY" -m etl.sexratio

echo "== 2/3 Инварианты =="
"$PY" checks/tests/test_invariants.py

echo "== 3/3 Сверка с заявленными результатами =="
"$PY" code/verify.py

echo "ГОТОВО: INF-20 воспроизведён и совпадает с заявленным."
