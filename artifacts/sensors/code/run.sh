#!/usr/bin/env bash
# Единственная точка входа: воспроизводит доли районов по трём датчикам
# (официальный ряд, GHS-POP, ночные огни), изменения долей, вердикты H1-H4,
# пост-хок и гейты V-1…V-5 из завендоренных входов; проверяет инварианты и
# сверяет с заявленным. Требования: Python >= 3.10, стандартная библиотека.
# Сеть не нужна.
set -euo pipefail
cd "$(dirname "$0")/.."
export PYTHONDONTWRITEBYTECODE=1
PY="${PYTHON:-python3}"

echo "== 1/3 Расчёт долей, изменений, гипотез и гейтов =="
"$PY" -m etl.sensors

echo "== 2/3 Инварианты =="
"$PY" checks/tests/test_invariants.py

echo "== 3/3 Сверка с заявленными результатами =="
"$PY" code/verify.py

echo "ГОТОВО: INF-21 воспроизведён и совпадает с заявленным."
